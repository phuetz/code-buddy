  function parseRaw() {
    var out = [];
    Object.keys(RAW).forEach(function (cat) {
      RAW[cat].forEach(function (row) {
        var space = row.indexOf(' ');
        if (space < 0) {
          out.push({ e: row, c: cat, k: '' });
          return;
        }
        out.push({ e: row.slice(0, space), c: cat, k: row.slice(space + 1) });
      });
    });
    return out;
  }

  var EMOJIS = parseRaw();

  function normalize(s) {
    return String(s || '')
      .toLowerCase()
      .normalize('NFD')
      .replace(/[\u0300-\u036f]/g, '');
  }

  function searchEmojis(query) {
    var q = normalize(query).trim();
    if (!q) return EMOJIS.slice();
    var parts = q.split(/\s+/);
    return EMOJIS.filter(function (item) {
      var hay = normalize(item.e + ' ' + item.k);
      return parts.every(function (part) {
        return hay.indexOf(part) !== -1;
      });
    });
  }

  function byCategory(id) {
    if (!id || id === 'recents') return [];
    return EMOJIS.filter(function (item) {
      return item.c === id;
    });
  }

  root.CODEBUDDY_EMOJI_DATA = {
    CATEGORIES: CATEGORIES,
    EMOJIS: EMOJIS,
    searchEmojis: searchEmojis,
    byCategory: byCategory,
  };
